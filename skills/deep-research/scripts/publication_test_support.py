def admit_frozen_legacy(monkeypatch, root: Path) -> dict:
    """Freeze this synthetic manifest only, not all legacy-layout fixtures."""
    import report_purpose

    path = root / 'manifest.json'
    manifest = json.loads(path.read_text()) if path.exists() else {
        'target': 'Synthetic legacy receipt unit', 'generated_at': '2000-01-01'}
    manifest.pop('report_purpose', None)
    path.write_text(json.dumps(manifest), encoding='utf-8')
    entry = {'root': str(root),
             'manifest_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
             'identity': copy.deepcopy(manifest)}
    monkeypatch.setattr(report_purpose, 'LEGACY_CAMPAIGNS', [entry])
    # The plain reader deliberately loads report_purpose from its sibling file,
    # not sys.modules. Give that independent resolver the same exact inventory;
    # never replace the resolver or broaden its byte/identity checks.
    execute_module = importlib.machinery.SourceFileLoader.exec_module

    def load_with_inventory(loader, module):
        execute_module(loader, module)
        if Path(getattr(module, '__file__', '')).resolve() == Path(report_purpose.__file__).resolve():
            monkeypatch.setattr(module, 'LEGACY_CAMPAIGNS', [entry])

    monkeypatch.setattr(importlib.machinery.SourceFileLoader, 'exec_module', load_with_inventory)
    assert report_purpose.resolve_report_purpose(manifest, root) == 'legacy'
    return manifest


def freeze_legacy_fixture(monkeypatch, root: Path) -> dict:
    """Admit one setup fixture and migrate only its already-matching snapshot.

    Freeze before adversarial edits. Never call this to repair a failed gate or
    to re-admit a mutated fixture; the inventory and stale bindings must hold.
    """
    from research_qa_repair import semantic_manifest_snapshot

    original = json.loads((root / 'manifest.json').read_text())
    manifest = admit_frozen_legacy(monkeypatch, root)
    receipt_path = root / 'qa/evidence-privacy-review.json'
    if receipt_path.is_file():
        receipt = json.loads(receipt_path.read_text())
        if receipt.get('semantic_manifest') == semantic_manifest_snapshot(original):
            receipt['semantic_manifest'] = semantic_manifest_snapshot(manifest)
            receipt_path.write_text(json.dumps(receipt), encoding='utf-8')
    return manifest


def run_offline_cli(script: Path, *args: str) -> subprocess.CompletedProcess:
    """Exercise a real read-only CLI without losing test-local monkeypatches."""
    argv = [str(script), *map(str, args)]
    stdout, stderr = io.StringIO(), io.StringIO()
    with patch.object(sys, 'argv', argv), redirect_stdout(stdout), redirect_stderr(stderr):
        try:
            runpy.run_path(str(script), run_name='__main__')
        except SystemExit as exc:
            assert isinstance(exc.code, int), exc.code
            returncode = exc.code
        else:
            returncode = 0
    return subprocess.CompletedProcess(argv, returncode, stdout=stdout.getvalue(), stderr=stderr.getvalue())


def run_frozen_legacy_cli(root: Path, script: Path, *args: str) -> subprocess.CompletedProcess:
    """Explicit frozen historical control for verifier-only legacy fixtures."""
    import pytest

    with pytest.MonkeyPatch.context() as monkeypatch:
        freeze_legacy_fixture(monkeypatch, root)
        return run_offline_cli(script, *args)


def bind_fixture_review_packet(root: Path, *, review_rel='qa/plain-brief-review.json') -> None:
    """Refresh exact packet bytes after a deliberate test setup metadata edit.

    Do not change verdicts, acceptance status, semantic snapshots, reader hashes,
    or dispositions. Negative fixtures remain negative at their intended seam.
    """
    import research_qa_repair as qa

    path = root / 'qa/editor-note-decisions.json'
    decisions = json.loads(path.read_text())
    review = json.loads((root / review_rel).read_text())
    _, history = qa._history_findings(root)
    paths = [review_rel, 'manifest.json', review['brief_path'], review['full_pack_path'],
             *history, *review.get('evidence_inputs', [])]
    for decision in decisions.get('decisions', []):
        paths.extend(decision.get('evidence_refs') or [])
    decisions['review_inputs'] = qa.build_review_packet(paths, root=root)
    path.write_text(json.dumps(decisions), encoding='utf-8')


def add_generated_provenance(root: Path, record: dict, *, editor_response=None, review_binding=None) -> None:
    """Populate modern calls/raw files without changing the saved reader bytes."""
    import plain_brief_rewrite as plain
    from reader_test_support import editor_pass, offline_plain_transport
    from research_settings import load_settings

    settings = load_settings(environ={})
    raw_dir = root / 'qa/synthetic-provider'
    body = (root / record['brief_path']).read_text()
    with offline_plain_transport(plain, responder=lambda role, *_:
            body if role == 'writer' else json.dumps(editor_response or editor_pass())), \
            plain.run_context(settings, raw_dir) as run:
        plain.call(record['writer_model'], 'Synthetic fixture writer.', body, role='writer')
        assert run.calls[-1]['status'] == 'success'
        assert run.calls[-1]['identity_verified'] is True
        editor = plain.call(record['editor_model'], 'Synthetic fixture review.', body, role='editor',
                            review_binding=review_binding)
        assert editor.acceptance_eligible is True
    calls = copy.deepcopy(run.calls)
    record.update(acceptance_eligible=True,
                  artifact_writers=copy.deepcopy([c for c in calls if c['role'] == 'writer']),
                  provenance={'schema_version': 'deep-research-served-calls-v1',
                              'calls': calls, 'attempts': copy.deepcopy(calls),
                              'final_editor_generation_id': calls[-1]['generation_id'],
                              'raw_response_paths': [str(Path(p).relative_to(root)) for p in run.raw_files]})


def synthetic_generation_table(root: Path) -> dict:
    """Read only retained synthetic raw responses, never editable call claims."""
    table = {}
    for path in (root / 'qa/synthetic-provider').glob('*.json'):
        saved = json.loads(path.read_text())
        for response in saved.get('raw_responses', []):
            assert response.get('synthetic') is True
            gid = response['id']
            assert gid.startswith('gen-SYNTHETIC-')
            table[gid] = {'model': response['model'], 'tokens_prompt': 100000}
    return table


def run_synthetic_export(root: Path, export: Path, *extra: str) -> subprocess.CompletedProcess:
    """Run the real CLI in-process with fail-closed synthetic generation HTTP.

    Keep sockets/alternate urllib paths denied. All output roots are explicit
    pytest paths. This avoids child-process monkeypatch loss and secret lookup.
    """
    import receipt_integrity as ri

    script = Path(__file__).with_name('export_deliverables.py')
    argv = [str(script), '--campaign-root', str(root), '--export-root', str(export), *extra]
    table = synthetic_generation_table(root)

    def deny(*args, **kwargs):
        raise AssertionError('live network forbidden in synthetic exporter tests')

    def provider(request, timeout):
        assert request.full_url.startswith(ri.GENERATION_URL)
        assert request.get_header('Authorization') == 'Bearer synthetic-export-test-only'
        gid = request.full_url[len(ri.GENERATION_URL):]
        assert gid in table, f'unknown synthetic generation: {gid}'
        return io.BytesIO(json.dumps({'data': table[gid]}).encode())

    output = io.StringIO()
    with patch.object(sys, 'argv', argv), redirect_stdout(output), redirect_stderr(output), \
            patch.dict(os.environ, {'OPENROUTER_API_KEY': 'synthetic-export-test-only'}), \
            patch.object(ri.time, 'sleep', lambda _: None), \
            patch.object(socket.socket, 'connect', deny), \
            patch.object(socket.socket, 'connect_ex', deny), \
            patch.object(socket, 'create_connection', deny), \
            patch.object(socket, 'getaddrinfo', deny), \
            patch.object(urllib.request.OpenerDirector, 'open', deny), \
            patch.object(urllib.request, 'urlopen', provider):
        try:
            runpy.run_path(str(script), run_name='__main__')
        except SystemExit as exc:
            assert isinstance(exc.code, int), exc.code
            returncode = exc.code
        else:
            returncode = 0
    return subprocess.CompletedProcess(argv, returncode, stdout=output.getvalue())


def run_frozen_legacy_export(root: Path, export: Path, *extra: str) -> subprocess.CompletedProcess:
    """Explicit historical inventory unit for old optional/two-output CLI tests.

    Only migrate an existing matching semantic snapshot after removing explicit
    purpose. Preserve verdicts, source hashes and intentional stale bindings.
    """
    import pytest
    with pytest.MonkeyPatch.context() as monkeypatch:
        freeze_legacy_fixture(monkeypatch, root)
        return run_synthetic_export(root, export, *extra)
